import { build } from 'esbuild';
import { readFileSync, unlinkSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
const tmp = join(tmpdir(), `centelha-f4-leitores-${process.pid}.mjs`);
await build({ entryPoints:['src/lib/ficha-formato.ts'], outfile:tmp, bundle:true, format:'esm', platform:'node', logLevel:'error' });
const { fichaParaGravar, fichaParaLeitura } = await import(pathToFileURL(tmp).href);
const combate = readFileSync('src/pages/mesa/combate.astro','utf8');
const grid = readFileSync('src/pages/mesa/grid.astro','utf8');
const linhaCombate = combate.match(/FICHAS = Object\.fromEntries\(\(fichas \|\| \[\]\)\.map\(\(f: any\) => \[f\.id, [^\]]+\]\)\);/)?.[0];
assert.ok(linhaCombate?.includes('fichaParaLeitura(f.ficha)'), 'combate deve converter a lista recebida');
const linhasGrid = grid.match(/if \(p\.ficha\) fichas\[p\.id\] = [^;]+;/g) || [];
assert.equal(linhasGrid.length,2,'Grid deve carregar fichas de jogador e mestre');
assert.ok(linhasGrid.every(x=>x.includes('fichaParaLeitura(p.ficha)')),'Grid deve converter as duas listas');
const linhaIniciativa = grid.match(/for \(const p of data \|\| \[\]\) fichas\[p\.id\] = [^;]+;/)?.[0];
assert.ok(linhaIniciativa?.includes('fichaParaLeitura(p.ficha)'),'Grid deve converter a lista da iniciativa');
const old = JSON.parse(readFileSync('scripts/fixtures/kael.json','utf8'));
old.arte = { fogo:2 }; old.efeito = { neblina:true };
const nova = fichaParaGravar(old), linha = {id:'pc',ficha:nova};
const montarCombate = new Function('fichas','fichaParaLeitura',`let FICHAS = {}; ${linhaCombate.replace(': any','')} return FICHAS;`);
const montarGrid = new Function('p','fichaParaLeitura',`const fichas = {}; ${linhasGrid[0]} return fichas;`);
const montarGridMestre = new Function('p','fichaParaLeitura',`const fichas = {}; ${linhasGrid[1]} return fichas;`);
const montarIniciativa = new Function('data','fichaParaLeitura',`const fichas = {}; ${linhaIniciativa} return fichas;`);
const verificar = f => {
  const ctx = { fichas:{pc:f} }, ficha = ctx.fichas.pc;
  assert.equal(ficha.attrs.raciocinio,old.attrs.raciocinio);
  assert.equal(ficha.attrs.destreza+ficha.skills.esquiva,old.attrs.destreza+old.skills.esquiva);
  assert.equal(ficha.virtues.bravura,old.virtues.valor);
  assert.equal(ficha.virtues.temperanca,old.virtues.temperanca);
  assert.equal(ficha.arte.fogo,2);
  assert.equal(ficha.efeito.neblina,true);
  assert.ok(ficha.conjuntos.find(x=>x.ativo));
};
for(const map of [montarCombate([linha],fichaParaLeitura),montarGrid(linha,fichaParaLeitura),
  montarGridMestre(linha,fichaParaLeitura),montarIniciativa([linha],fichaParaLeitura)]) verificar(map.pc);
assert.throws(()=>verificar(nova),'controle negativo: a ficha nova crua deve falhar');
unlinkSync(tmp);
console.log('F4 B2: combate, Grid jogador, Grid mestre e iniciativa leem ficha nova; controle cru falha');
