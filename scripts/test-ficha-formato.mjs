import { build } from 'esbuild';
import { readFileSync, unlinkSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
import { fichaSchema, refsExistem } from './ficha-schema.mjs';
import { achataCatalogo } from './lib-equip.mjs';
const out = join(tmpdir(), `centelha-ficha41-${process.pid}.mjs`);
await build({ entryPoints: ['src/lib/ficha-formato.ts'], outfile: out, bundle: true, format: 'esm', platform: 'node', logLevel: 'error' });
const { fichaParaGravar, fichaParaLeitura } = await import(pathToFileURL(out).href);
const old = JSON.parse(readFileSync('scripts/fixtures/kael.json', 'utf8'));
const novo = fichaParaGravar(old);
assert.equal(novo.nome, old.id.nome);
assert.equal(novo.atributos.forca, old.attrs.forca);
assert.equal(novo.virtudes.bravura, old.virtues.valor);
assert.equal(novo.vontade, old.willpower);
assert.equal(novo.equipamento.conjuntos[0].maoHabil.ref, old.conjuntos[0].habil.ref);
assert.ok(!('attrs' in novo) && !('id' in novo) && !('defSpec' in novo));
assert.ok(fichaSchema.safeParse(old).success && fichaSchema.safeParse(novo).success);
assert.ok(!fichaSchema.safeParse({ ...novo, atributos: undefined }).success);
const antigoLido = fichaParaLeitura(novo);
assert.equal(antigoLido.attrs.forca, old.attrs.forca);
assert.equal(antigoLido.virtues.bravura, old.virtues.valor);
assert.equal(antigoLido.conjuntos[0].habil.ref, old.conjuntos[0].habil.ref);
assert.deepEqual(fichaParaGravar(novo), novo);
const armas = achataCatalogo(JSON.parse(readFileSync('src/data/armas.json', 'utf8')));
const escudos = achataCatalogo(JSON.parse(readFileSync('src/data/escudos.json', 'utf8')));
const armaduras = achataCatalogo(JSON.parse(readFileSync('src/data/armaduras.json', 'utf8')));
assert.deepEqual(refsExistem(novo, { armas, escudos, armaduras }), []);
const ruim = structuredClone(novo); ruim.equipamento.conjuntos[0].maoHabil.ref = 'a:arma-que-nao-existe';
assert.ok(refsExistem(ruim, { armas, escudos, armaduras }).length > 0);
assert.equal(fichaParaGravar({ ...old, id: { ...old.id, altura: '1,85 m', peso: '90 kg' } }).corpo.altura, 1.85);
assert.equal(fichaParaGravar({ ...old, id: { ...old.id, altura: '1,85 m', peso: '90 kg' }, corpo: {} }).corpo.massa, 90);
unlinkSync(out);
console.log('Ficha 41: formatos velho e novo, ida e volta, Bravura, equipamento e controles negativos OK');
